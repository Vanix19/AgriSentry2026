// Copies the web dashboard's translation table into the mobile app so both stay in sync.
// Run from agrisentry-mobile: node scripts/sync-translations.js
const fs = require("fs");
const path = require("path");

const source = path.join(__dirname, "../../Agrisentry/public/js/system-translations.js");
const target = path.join(__dirname, "../constants/translations-web.ts");
const rows = fs.readFileSync(source, "utf8").split("\n").filter((line) => line.split("|").length === 4);

fs.writeFileSync(target, "// Generated by scripts/sync-translations.js from Agrisentry/public/js/system-translations.js. Do not edit.\n"
  + "// English | Cebuano | Filipino | Spanish\n"
  + `export const WEB_TRANSLATION_ROWS: string = ${JSON.stringify(rows.join("\n"))};\n`);
console.log(`Wrote ${rows.length} rows to ${path.relative(process.cwd(), target)}`);
